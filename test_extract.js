function __extractFn(src, name) {
  const start = src.indexOf("function " + name);
  if (start < 0) throw new Error("未找到函数 " + name);
  let i = src.indexOf("{", start), depth = 0;
  for (; i < src.length; i++) {
    if (src[i] === "{") depth++;
    else if (src[i] === "}") { depth--; if (depth === 0) { i++; break; } }
  }
  return src.slice(start, i);
}
