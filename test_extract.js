function titlePassesFilter(title, base) {
  const blockWords = ['函授'];
  for (const w of blockWords) if (w && title.indexOf(w) >= 0) return false;
  const b = normText(base || '');
  if (b && !normText(title).includes(b)) return false;
  return true;
}

